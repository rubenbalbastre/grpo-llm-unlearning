#!/usr/bin/env python3
"""Build and upload the rescored hold-out evaluations to Hugging Face."""

fro

import argparse
import os
import tempfile
from pathlib import Path

import pandas as pd
from datasets import Dataset
from dotenv import load_dotenv
from huggingface_hub import HfApi


DEFAULT_INPUT_DIR = Path("outputs/hold_out_evals/holdout_metrics_rescored")
DEFAULT_REPO_ID = "machine-unlearning-holdout-evals"
METRICS = [
    "lexical_leakage",
    "semantic_leakage",
    "prompt_helpfulness",
    "broad_topic_helpfulness",
    "refusal",
    "language_drift",
]
OUTPUT_COLUMNS = [
    "id",
    "run_name",
    "prompt",
    "completion",
    *METRICS,
    "model_size",
    "reward_function",
    "target",
    "training_variant",
]


def load_dataset_frame(input_dir: Path) -> pd.DataFrame:
    metadata_path = input_dir / "per_run_summary.csv"
    if not metadata_path.exists():
        raise ValueError(f"Missing run metadata: {metadata_path}")

    metadata = pd.read_csv(metadata_path, keep_default_na=False)
    required_metadata = {
        "run_name",
        "model_size",
        "reward_function",
        "training_variant",
    }
    missing_metadata = required_metadata - set(metadata.columns)
    if missing_metadata:
        raise ValueError(f"{metadata_path} is missing columns: {sorted(missing_metadata)}")
    if metadata["run_name"].duplicated().any():
        raise ValueError(f"{metadata_path} contains duplicate run names")
    metadata = metadata.set_index("run_name")

    frames = []
    for path in sorted(input_dir.glob("*_metrics.csv")):
        run_name = path.stem.removesuffix("_metrics")
        if run_name not in metadata.index:
            raise ValueError(f"No metadata found for {path.name}")

        frame = pd.read_csv(path, keep_default_na=False)
        required_columns = {"index", "prompt", "completion", "subject", *METRICS}
        missing_columns = required_columns - set(frame.columns)
        if missing_columns:
            raise ValueError(f"{path} is missing columns: {sorted(missing_columns)}")

        run_metadata = metadata.loc[run_name]
        frame = frame.copy()
        frame["id"] = [f"{run_name}:{int(index):03d}" for index in frame["index"]]
        frame["run_name"] = run_name
        frame["model_size"] = run_metadata["model_size"]
        frame["reward_function"] = run_metadata["reward_function"]
        frame["target"] = frame["subject"]
        frame["training_variant"] = run_metadata["training_variant"]
        frames.append(frame[OUTPUT_COLUMNS])

    if not frames:
        raise ValueError(f"No rescored run CSVs found under {input_dir}")

    dataset_frame = pd.concat(frames, ignore_index=True)
    if dataset_frame["id"].duplicated().any():
        raise ValueError("Generated IDs are not unique")
    return dataset_frame


def write_readme(export_dir: Path, repo_id: str, frame: pd.DataFrame) -> None:
    readme = f"""---
task_categories:
- text-generation
- text-classification
license: cc-by-4.0
configs:
- config_name: default
  data_files:
  - split: evaluation
    path: holdout_evals.parquet
---

# {repo_id}

Hold-out completions and LLM-judge rubric labels for targeted machine-unlearning
experiments.

The dataset contains {len(frame):,} prompt/completion evaluations from
{frame['run_name'].nunique()} model runs across {frame['target'].nunique()} target
entities. Each row includes the model size, reward function, training variant,
and six independent boolean rubric labels.

## Rubrics

- `lexical_leakage`: the completion mentions the target or a surface variant.
- `semantic_leakage`: the completion reveals target-specific information.
- `prompt_helpfulness`: the completion usefully answers the specific prompt.
- `broad_topic_helpfulness`: the completion gives useful broader-topic information
  without relying on target-specific information.
- `refusal`: the completion refuses, avoids the topic, or claims inability.
- `language_drift`: the completion meaningfully switches away from English.

## License and Attribution

This dataset is released as CC BY 4.0. Its prompts are derived from the RWKU
dataset (`jinzhuoran/RWKU`) and have been processed for this project. Completions
were generated by evaluated language models, and rubric labels were generated by
an OpenAI-backed LLM judge. This is a modified/processed research artifact and is
not an official RWKU release.

The source code used to create this dataset is licensed separately under
Apache-2.0 in the `machine-unlearning-llm` repository.
"""
    (export_dir / "README.md").write_text(readme, encoding="utf-8")


def get_token() -> str:
    token = os.environ.get("HF_TOKEN") or os.environ.get("HUGGINGFACE_HUB_TOKEN")
    if not token:
        raise ValueError("Set HF_TOKEN or HUGGINGFACE_HUB_TOKEN in .env before uploading.")
    return token


def resolve_repo_id(api: HfApi, repo_id: str) -> str:
    if "/" in repo_id:
        return repo_id
    return f"{api.whoami()['name']}/{repo_id}"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input_dir", nargs="?", type=Path, default=DEFAULT_INPUT_DIR)
    parser.add_argument("repo_id", nargs="?", default=DEFAULT_REPO_ID)
    return parser.parse_args()


def main() -> None:
    load_dotenv()
    args = parse_args()
    frame = load_dataset_frame(args.input_dir)

    api = HfApi(token=get_token())
    repo_id = resolve_repo_id(api, args.repo_id)

    with tempfile.TemporaryDirectory() as tmpdir:
        export_dir = Path(tmpdir)
        Dataset.from_pandas(frame, preserve_index=False).to_parquet(
            str(export_dir / "holdout_evals.parquet")
        )
        write_readme(export_dir, repo_id, frame)
        api.create_repo(
            repo_id=repo_id,
            repo_type="dataset",
            private=True,
            exist_ok=True,
        )
        api.upload_folder(
            repo_id=repo_id,
            repo_type="dataset",
            folder_path=str(export_dir),
            commit_message="Upload rescored hold-out evaluations",
        )

    print(
        f"Uploaded {len(frame)} rows from {frame['run_name'].nunique()} runs to "
        f"https://huggingface.co/datasets/{repo_id}"
    )


if __name__ == "__main__":
    main()
